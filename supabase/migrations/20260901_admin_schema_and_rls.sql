-- 13. ATOMIC ORDER CREATION & ROW-LOCKED STOCK DECREMENT RPC
-- =========================================================================
CREATE OR REPLACE FUNCTION public.create_order_atomic(
  p_user_id UUID,
  p_customer_name TEXT,
  p_customer_email TEXT,
  p_customer_phone TEXT,
  p_shipping_address JSONB,
  p_items JSONB,
  p_payment_method TEXT,
  p_coupon_code TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_item JSONB;
  v_prod RECORD;
  v_var RECORD;
  v_subtotal NUMERIC(12, 2) := 0;
  v_discount NUMERIC(12, 2) := 0;
  v_shipping NUMERIC(12, 2) := 120;
  v_total NUMERIC(12, 2) := 0;
  v_order_items JSONB := '[]'::jsonb;
  v_item_price NUMERIC(12, 2);
  v_item_name TEXT;
  v_item_img TEXT;
  v_qty INT;
  v_coupon RECORD;
  v_order_id BIGINT;
BEGIN
  IF jsonb_array_length(p_items) = 0 THEN
    RAISE EXCEPTION 'Cannot create an empty order.';
  END IF;

  -- 1. Loop through items with row-level locks (FOR UPDATE)
  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items)
  LOOP
    v_qty := (v_item->>'quantity')::INT;
    IF v_qty <= 0 THEN
      RAISE EXCEPTION 'Invalid item quantity: %', v_qty;
    END IF;

    IF (v_item->>'variation_id') IS NOT NULL AND (v_item->>'variation_id') != 'null' AND (v_item->>'variation_id') != '' THEN
      -- Lock variation row
      SELECT * INTO v_var
      FROM public.product_variations
      WHERE id = (v_item->>'variation_id')::BIGINT
      FOR UPDATE;

      IF NOT FOUND THEN
        RAISE EXCEPTION 'Product variation not found (id: %)', v_item->>'variation_id';
      END IF;

      -- Check variation stock
      IF v_var.stock < v_qty THEN
        RAISE EXCEPTION 'Insufficient stock for % (%). Available: %, Requested: %',
          v_var.color, v_var.storage, v_var.stock, v_qty;
      END IF;

      -- Fetch parent product
      SELECT * INTO v_prod FROM public.products WHERE id = v_var.product_id FOR UPDATE;
      
      v_item_price := COALESCE(v_var.price, v_prod.price);
      v_item_name := v_prod.name || ' (' || COALESCE(v_var.color, '') || ' ' || COALESCE(v_var.storage, '') || ')';
      v_item_img := COALESCE(v_var.image_url, v_prod.image_url);

      -- Decrement variation stock atomically
      UPDATE public.product_variations
      SET stock = stock - v_qty
      WHERE id = v_var.id;

      -- Also decrement parent product aggregate stock
      UPDATE public.products
      SET stock = GREATEST(0, stock - v_qty)
      WHERE id = v_prod.id;

    ELSE
      -- Lock base product row
      SELECT * INTO v_prod
      FROM public.products
      WHERE id = (v_item->>'product_id')::BIGINT
      FOR UPDATE;

      IF NOT FOUND THEN
        RAISE EXCEPTION 'Product not found (id: %)', v_item->>'product_id';
      END IF;

      -- Check product stock
      IF v_prod.stock < v_qty THEN
        RAISE EXCEPTION 'Insufficient stock for "%". Available: %, Requested: %',
          v_prod.name, v_prod.stock, v_qty;
      END IF;

      v_item_price := v_prod.price;
      v_item_name := v_prod.name;
      v_item_img := v_prod.image_url;

      -- Decrement product stock atomically
      UPDATE public.products
      SET stock = stock - v_qty
      WHERE id = v_prod.id;
    END IF;

    -- Calculate line subtotal
    v_subtotal := v_subtotal + (v_item_price * v_qty);

    -- Build snapshot of order item
    v_order_items := v_order_items || jsonb_build_object(
      'product_id', v_prod.id,
      'variation_id', CASE WHEN v_var.id IS NOT NULL THEN v_var.id ELSE NULL END,
      'name', v_item_name,
      'price', v_item_price,
      'quantity', v_qty,
      'image_url', v_item_img
    );
  END LOOP;

  -- 2. Server-side coupon verification
  IF p_coupon_code IS NOT NULL AND p_coupon_code <> '' THEN
    SELECT * INTO v_coupon
    FROM public.coupons
    WHERE UPPER(code) = UPPER(p_coupon_code)
      AND is_active = true
      AND (expires_at IS NULL OR expires_at > NOW());

    IF FOUND THEN
      IF v_subtotal >= v_coupon.min_order_amount THEN
        IF v_coupon.discount_type = 'percentage' THEN
          v_discount := (v_subtotal * v_coupon.discount_value) / 100;
          IF v_coupon.max_discount_amount IS NOT NULL THEN
            v_discount := LEAST(v_discount, v_coupon.max_discount_amount);
          END IF;
        ELSE
          v_discount := LEAST(v_subtotal, v_coupon.discount_value);
        END IF;
      END IF;
    END IF;
  END IF;

  -- Free delivery for orders above ৳50,000
  IF v_subtotal > 50000 THEN
    v_shipping := 0;
  END IF;

  v_total := GREATEST(0, (v_subtotal - v_discount) + v_shipping);

  -- 3. Insert into orders table
  INSERT INTO public.orders (
    user_id,
    customer_name,
    customer_email,
    customer_phone,
    shipping_address,
    items,
    total_amount,
    payment_method,
    payment_status,
    status
  ) VALUES (
    p_user_id,
    p_customer_name,
    p_customer_email,
    p_customer_phone,
    p_shipping_address,
    v_order_items,
    v_total,
    p_payment_method,
    'unpaid',
    'pending'
  ) RETURNING id INTO v_order_id;

  -- 4. Clear cart items for user if logged in
  IF p_user_id IS NOT NULL THEN
    DELETE FROM public.cart_items WHERE user_id = p_user_id;
  END IF;

  -- 5. Return complete order summary
  RETURN jsonb_build_object(
    'success', true,
    'order_id', v_order_id,
    'subtotal', v_subtotal,
    'discount_amount', v_discount,
    'shipping_charge', v_shipping,
    'total_amount', v_total,
    'payment_method', p_payment_method,
    'status', 'pending'
  );
END;
$$;

